#!/usr/bin/env python3
"""
Analysis 01: Source-level dataset composition analysis

Purpose
-------
Summarise how many records each included source contributes to the merged
drug-disease dataset before and after source-level schema-record deduplication.

This script reports:

  1. Per-source raw merged row counts
  2. Per-source deduplicated row counts
  3. Duplicates removed per source
  4. Duplicate-removal percentage per source
  5. Unique normalised drug names per source
  6. Unique normalised disease/condition names per source
  7. Unique normalised drug-disease name pairs per source
  8. A manuscript-style description

Important
---------
Deduplication itself is performed upstream in Analysis_00_MergeDatabases.py.

This script does NOT re-deduplicate the dataset. It only summarises the already
generated merged and deduplicated files.

For unique drug, disease, and drug-disease pair counts, this script uses
normalised names only:

  - normalised drug_name
  - normalised disease_or_condition_name
  - normalised drug_name || normalised disease_or_condition_name

Drug and disease identifiers are intentionally NOT used for these unique
coverage counts because different sources use different identifier namespaces.

No output files are generated by default.

Expected input files
--------------------
data/processed/ALL_INCLUDED_SOURCES_drug_disease_merged.csv
data/processed/ALL_INCLUDED_SOURCES_drug_disease_deduplicated.csv

Run
---
python Analysis_01_Source_level_dataset_composition.py

Optional:
python Analysis_01_Source_level_dataset_composition.py > Analysis_01_output.txt

Requirements
------------
pip install polars
"""

from pathlib import Path
import polars as pl


# ============================================================
# POLARS DISPLAY CONFIG
# ============================================================

pl.Config.set_tbl_rows(-1)
pl.Config.set_tbl_cols(-1)
pl.Config.set_tbl_width_chars(0)
pl.Config.set_fmt_str_lengths(200)


# ============================================================
# CONFIG
# ============================================================

BASE = Path(
    "/data/ascher02/uqmmune1/ANNOVAR/drug_disease_data/"
    "drug-disease-mapping/data/processed"
)

MERGED_FILE = BASE / "ALL_INCLUDED_SOURCES_drug_disease_merged.csv"
DEDUP_FILE = BASE / "ALL_INCLUDED_SOURCES_drug_disease_deduplicated.csv"

REQUIRED_COLUMNS = [
    "drug_name",
    "disease_or_condition_name",
    "source",
]

OPTIONAL_CONTEXT_COLUMNS = [
    "drug_identifier",
    "drug_identifier_type",
    "disease_or_condition_identifier",
    "disease_or_condition_identifier_type",
    "relationship_type",
    "evidence_type",
]


# ============================================================
# HELPERS
# ============================================================

def print_section(title: str) -> None:
    print("\n" + "=" * 120)
    print(title)
    print("=" * 120)


def read_csv_checked(path: Path, label: str) -> pl.DataFrame:
    """
    Read a CSV file and check that required columns are present.
    """
    if not path.exists():
        raise FileNotFoundError(f"{label} file not found: {path}")

    if path.stat().st_size == 0:
        raise RuntimeError(f"{label} file is empty: {path}")

    df = pl.read_csv(
        path,
        infer_schema_length=10000,
        ignore_errors=True,
        null_values=[
            "",
            "NA",
            "N/A",
            "nan",
            "NaN",
            "None",
            "NULL",
            "null",
        ],
    )

    if df.height == 0:
        raise RuntimeError(f"{label} file has zero rows: {path}")

    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]

    if missing:
        raise RuntimeError(
            f"{label} file is missing required columns: {missing}\n"
            f"Available columns: {df.columns}"
        )

    return df


def clean_required_columns(df: pl.DataFrame) -> pl.DataFrame:
    """
    Clean required text columns.

    This keeps the original human-readable names but removes extra whitespace.
    """
    return df.with_columns(
        [
            pl.col(col)
            .cast(pl.Utf8)
            .fill_null("")
            .str.strip_chars()
            .str.replace_all(r"\s+", " ")
            .alias(col)
            for col in REQUIRED_COLUMNS
        ]
    )


def normalise_name_expr(col: str) -> pl.Expr:
    """
    Conservative vectorised name normalisation.

    This is used for counting unique drugs, diseases/conditions, and
    drug-disease name pairs.

    Steps:
      - cast to string
      - lowercase
      - strip leading/trailing spaces
      - replace separators/punctuation with spaces
      - remove remaining non-alphanumeric characters
      - collapse repeated whitespace

    This is NOT full chemical or disease ontology normalisation.
    """
    return (
        pl.col(col)
        .cast(pl.Utf8)
        .fill_null("")
        .str.to_lowercase()
        .str.strip_chars()
        .str.replace_all(r"[_/\\|,:;]+", " ")
        .str.replace_all(r"[\(\)\[\]\{\}\"'`]", " ")
        .str.replace_all(r"[-–—]+", " ")
        .str.replace_all(r"[^a-z0-9]+", " ")
        .str.replace_all(r"\s+", " ")
        .str.strip_chars()
    )


def add_normalised_name_keys(df: pl.DataFrame) -> pl.DataFrame:
    """
    Add normalised-name-based keys.

    Important:
    ----------
    These keys are based on names only.

    We intentionally do NOT use drug_identifier or disease_or_condition_identifier
    for these counts, because cross-source identifier namespaces differ.

    Added columns:
      - _normalised_drug_name
      - _normalised_disease_or_condition_name
      - _normalised_drug_disease_name_pair
    """
    return (
        df.with_columns(
            [
                normalise_name_expr("drug_name").alias("_normalised_drug_name"),
                normalise_name_expr("disease_or_condition_name").alias(
                    "_normalised_disease_or_condition_name"
                ),
            ]
        )
        .with_columns(
            (
                pl.col("_normalised_drug_name")
                + pl.lit(" || ")
                + pl.col("_normalised_disease_or_condition_name")
            ).alias("_normalised_drug_disease_name_pair")
        )
    )


def summarise_by_source(
    merged: pl.DataFrame,
    dedup: pl.DataFrame,
) -> pl.DataFrame:
    """
    Summarise source-level composition.

    Row counts:
      - raw_merged_rows are counted from merged file
      - deduplicated_rows are counted from deduplicated file
      - duplicates_removed = raw_merged_rows - deduplicated_rows

    Unique counts:
      - calculated from the deduplicated dataset
      - based on normalised names only, not identifiers
    """
    merged = add_normalised_name_keys(clean_required_columns(merged))
    dedup = add_normalised_name_keys(clean_required_columns(dedup))

    merged_summary = (
        merged.group_by("source")
        .agg(
            [
                pl.len().alias("raw_merged_rows"),

                pl.col("_normalised_drug_name")
                .filter(pl.col("_normalised_drug_name") != "")
                .n_unique()
                .alias("raw_unique_normalised_drug_names"),

                pl.col("_normalised_disease_or_condition_name")
                .filter(pl.col("_normalised_disease_or_condition_name") != "")
                .n_unique()
                .alias("raw_unique_normalised_disease_names"),

                pl.col("_normalised_drug_disease_name_pair")
                .filter(
                    (pl.col("_normalised_drug_name") != "")
                    & (pl.col("_normalised_disease_or_condition_name") != "")
                )
                .n_unique()
                .alias("raw_unique_normalised_drug_disease_name_pairs"),
            ]
        )
    )

    dedup_summary = (
        dedup.group_by("source")
        .agg(
            [
                pl.len().alias("deduplicated_rows"),

                pl.col("_normalised_drug_name")
                .filter(pl.col("_normalised_drug_name") != "")
                .n_unique()
                .alias("dedup_unique_normalised_drug_names"),

                pl.col("_normalised_disease_or_condition_name")
                .filter(pl.col("_normalised_disease_or_condition_name") != "")
                .n_unique()
                .alias("dedup_unique_normalised_disease_names"),

                pl.col("_normalised_drug_disease_name_pair")
                .filter(
                    (pl.col("_normalised_drug_name") != "")
                    & (pl.col("_normalised_disease_or_condition_name") != "")
                )
                .n_unique()
                .alias("dedup_unique_normalised_drug_disease_name_pairs"),
            ]
        )
    )

    summary = (
        merged_summary.join(
            dedup_summary,
            on="source",
            how="full",
            coalesce=True,
        )
        .fill_null(0)
        .with_columns(
            (
                pl.col("raw_merged_rows") - pl.col("deduplicated_rows")
            ).alias("duplicates_removed")
        )
        .with_columns(
            pl.when(pl.col("raw_merged_rows") > 0)
            .then(
                (
                    pl.col("duplicates_removed")
                    / pl.col("raw_merged_rows")
                    * 100
                ).round(3)
            )
            .otherwise(0)
            .alias("duplicates_removed_percent")
        )
        .select(
            [
                "source",
                "raw_merged_rows",
                "deduplicated_rows",
                "duplicates_removed",
                "duplicates_removed_percent",
                "dedup_unique_normalised_drug_names",
                "dedup_unique_normalised_disease_names",
                "dedup_unique_normalised_drug_disease_name_pairs",
            ]
        )
        .sort("deduplicated_rows", descending=True)
    )

    return summary


def calculate_total_summary(summary: pl.DataFrame) -> dict:
    """
    Calculate total summary values from the per-source table.
    """
    total_raw = int(summary["raw_merged_rows"].sum())
    total_dedup = int(summary["deduplicated_rows"].sum())
    total_removed = int(summary["duplicates_removed"].sum())
    n_sources = int(summary["source"].n_unique())

    if total_raw > 0:
        total_removed_percent = round(total_removed / total_raw * 100, 3)
    else:
        total_removed_percent = 0.0

    top = summary.sort("deduplicated_rows", descending=True).row(0, named=True)

    return {
        "total_raw": total_raw,
        "total_dedup": total_dedup,
        "total_removed": total_removed,
        "total_removed_percent": total_removed_percent,
        "n_sources": n_sources,
        "top_source": top["source"],
        "top_rows": int(top["deduplicated_rows"]),
    }


def print_full_polars_table(df: pl.DataFrame) -> None:
    """
    Print the complete Polars table without row or column truncation.
    """
    with pl.Config(
        tbl_rows=-1,
        tbl_cols=-1,
        tbl_width_chars=0,
        fmt_str_lengths=200,
    ):
        print(df)


def print_dataset_description(summary: pl.DataFrame) -> None:
    values = calculate_total_summary(summary)

    print_section("DESCRIPTION")

    print(
        "Analysis 01 summarises the source-level composition of the harmonised "
        "drug-disease dataset. The purpose is to quantify how many records each "
        "database contributes before and after source-level schema-record "
        "deduplication, and to report normalised-name-based drug, disease, and "
        "drug-disease pair coverage by source."
    )

    print()

    print(
        f"The merged dataset contains {values['total_raw']:,} source-level rows "
        f"before deduplication and {values['total_dedup']:,} rows after "
        f"deduplication. A total of {values['total_removed']:,} repeated "
        f"source-level schema records were removed, corresponding to "
        f"{values['total_removed_percent']:.3f}% of the raw merged dataset. "
        f"The dataset contains records from {values['n_sources']:,} loaded "
        f"sources. The largest contributor after deduplication is "
        f"{values['top_source']}, with {values['top_rows']:,} rows."
    )

    print()

    print(
        "Unique drug, disease/condition, and drug-disease pair counts in this "
        "analysis are based on normalised names only. Drug and disease identifiers "
        "are intentionally not used for these coverage counts because different "
        "sources use different identifier namespaces. Therefore, these counts "
        "represent normalised-name-level coverage rather than full chemical or "
        "ontology-level equivalence."
    )

    print()

    print(
        "Important interpretation: these counts describe dataset composition only. "
        "They do not imply that all records represent approved drug indications. "
        "Each source retains its own evidence semantics through relationship_type "
        "and evidence_type fields."
    )


def print_manuscript_table_tsv(summary: pl.DataFrame) -> None:
    """
    Print a clean TSV-style table that can be copied into spreadsheet/LaTeX conversion.
    """
    print_section("COPY-FRIENDLY TABLE")

    print(
        "Source\t"
        "Raw merged rows\t"
        "Deduplicated rows\t"
        "Duplicates removed\t"
        "Duplicates removed (%)\t"
        "Unique normalised drug names\t"
        "Unique normalised disease/condition names\t"
        "Unique normalised drug-disease name pairs"
    )

    for row in summary.iter_rows(named=True):
        print(
            f"{row['source']}\t"
            f"{int(row['raw_merged_rows'])}\t"
            f"{int(row['deduplicated_rows'])}\t"
            f"{int(row['duplicates_removed'])}\t"
            f"{float(row['duplicates_removed_percent']):.3f}\t"
            f"{int(row['dedup_unique_normalised_drug_names'])}\t"
            f"{int(row['dedup_unique_normalised_disease_names'])}\t"
            f"{int(row['dedup_unique_normalised_drug_disease_name_pairs'])}"
        )

    totals = calculate_total_summary(summary)

    print(
        f"Total\t"
        f"{totals['total_raw']}\t"
        f"{totals['total_dedup']}\t"
        f"{totals['total_removed']}\t"
        f"{totals['total_removed_percent']:.3f}\t"
        f"--\t"
        f"--\t"
        f"--"
    )


# ============================================================
# MAIN
# ============================================================

def main() -> None:
    print_section("ANALYSIS 01: SOURCE-LEVEL DATASET COMPOSITION")

    print(f"[MERGED FILE] {MERGED_FILE}")
    print(f"[DEDUP FILE]  {DEDUP_FILE}")

    merged = read_csv_checked(MERGED_FILE, "Merged")
    dedup = read_csv_checked(DEDUP_FILE, "Deduplicated")

    print()
    print(f"[MERGED ROWS] {merged.height:,}")
    print(f"[DEDUP ROWS]  {dedup.height:,}")

    summary = summarise_by_source(merged, dedup)

    print_section("SOURCE-LEVEL COMPOSITION TABLE")
    print_full_polars_table(summary)

    print_manuscript_table_tsv(summary)

    print_dataset_description(summary)

    print_section("DONE")


if __name__ == "__main__":
    main()